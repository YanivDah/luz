ALTER TABLE services
ADD CONSTRAINT services_id_business_unique
UNIQUE (id, business_id);

CREATE TABLE customers (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    business_id BIGINT NOT NULL REFERENCES businesses(id),
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    CONSTRAINT customers_business_phone_unique UNIQUE (business_id, phone),
    CONSTRAINT customers_id_business_unique UNIQUE (id, business_id)
);

CREATE TABLE appointments(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    business_id BIGINT NOT NULL REFERENCES businesses(id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    customer_name VARCHAR(255) NOT NULL,
    customer_phone VARCHAR(20) NOT NULL,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    price_at_booking INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT appointments_status_check
        CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    CONSTRAINT appointments_time_check
        CHECK (end_time > start_time),
    CONSTRAINT appointments_price_check
        CHECK (price_at_booking >= 0),
    CONSTRAINT appointments_customer_business_fk 
        FOREIGN KEY (customer_id, business_id) REFERENCES customers(id, business_id),
    CONSTRAINT appointments_service_business_fk 
        FOREIGN KEY (service_id, business_id) REFERENCES services(id, business_id)
);

